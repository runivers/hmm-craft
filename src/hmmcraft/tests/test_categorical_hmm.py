import numpy as np
import pytest
from numpy.testing import assert_allclose

from hmmcraft import hmm

from . import assert_log_likelihood_increasing, normalized


def _fit_bytes(model):
    """The fitted arrays and the history of the fit, as bytes."""
    state = {
        name: (np.asarray(v).dtype.str, np.shape(v), np.asarray(v).tobytes())
        for name, v in vars(model).items()
        if name.endswith("_") and name != "monitor_"
    }
    state["monitor_.history"] = list(model.monitor_.history)
    return state


class TestCategoricalAgainstWikipedia:
    """
    Examples from Wikipedia:

    - http://en.wikipedia.org/wiki/Hidden_Markov_model
    - http://en.wikipedia.org/wiki/Viterbi_algorithm
    """

    def new_hmm(self, impl):
        n_components = 2  # ['Rainy', 'Sunny']
        n_features = 3  # ['walk', 'shop', 'clean']
        h = hmm.CategoricalHMM(n_components, implementation=impl)
        h.n_features = n_features
        h.startprob_ = np.array([0.6, 0.4])
        h.transmat_ = np.array([[0.7, 0.3], [0.4, 0.6]])
        h.emissionprob_ = np.array([[0.1, 0.4, 0.5], [0.6, 0.3, 0.1]])
        return h

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_decode_viterbi(self, implementation):
        # From http://en.wikipedia.org/wiki/Viterbi_algorithm:
        # "This reveals that the observations ['walk', 'shop', 'clean']
        #  were most likely generated by states ['Sunny', 'Rainy', 'Rainy'],
        #  with probability 0.01344."
        h = self.new_hmm(implementation)
        X = [[0], [1], [2]]
        log_prob, state_sequence = h.decode(X, algorithm="viterbi")
        assert round(np.exp(log_prob), 5) == 0.01344
        assert_allclose(state_sequence, [1, 0, 0])

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_decode_map(self, implementation):
        X = [[0], [1], [2]]
        h = self.new_hmm(implementation)
        _log_prob, state_sequence = h.decode(X, algorithm="map")
        assert_allclose(state_sequence, [1, 0, 0])

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_predict(self, implementation):
        X = [[0], [1], [2]]
        h = self.new_hmm(implementation)
        state_sequence = h.predict(X)
        posteriors = h.predict_proba(X)
        assert_allclose(state_sequence, [1, 0, 0])
        assert_allclose(
            posteriors,
            [
                [0.23170303, 0.76829697],
                [0.62406281, 0.37593719],
                [0.86397706, 0.13602294],
            ],
            rtol=0,
            atol=1e-6,
        )


class TestCategoricalHMM:
    n_components = 2
    n_features = 3

    def new_hmm(self, impl):
        h = hmm.CategoricalHMM(self.n_components, implementation=impl)
        h.startprob_ = np.array([0.6, 0.4])
        h.transmat_ = np.array([[0.7, 0.3], [0.4, 0.6]])
        h.emissionprob_ = np.array([[0.1, 0.4, 0.5], [0.6, 0.3, 0.1]])
        return h

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_n_features(self, implementation):
        sequences, _ = self.new_hmm(implementation).sample(500)
        # set n_features
        model = hmm.CategoricalHMM(
            n_components=2, implementation=implementation
        )

        assert_log_likelihood_increasing(model, sequences, [500], 10)
        assert model.n_features == 3

        # Respect n_features
        model = hmm.CategoricalHMM(
            n_components=2, implementation=implementation, n_features=5
        )

        assert_log_likelihood_increasing(model, sequences, [500], 10)
        assert model.n_features == 5

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_attributes(self, implementation):
        with pytest.raises(ValueError):
            h = self.new_hmm(implementation)
            h.emissionprob_ = []
            h._check()
        with pytest.raises(ValueError):
            h.emissionprob_ = np.zeros(
                (self.n_components - 2, self.n_features)
            )
            h._check()
        for row in ([1.2, -0.2, 0.0], [np.nan, 0.5, 0.5]):
            h = self.new_hmm(implementation)
            h.emissionprob_ = np.array([row, [0.6, 0.3, 0.1]])
            with pytest.raises(ValueError, match="emissionprob_"):
                h._check()

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    @pytest.mark.parametrize("method", ["score", "predict"])
    def test_negative_transmat_raises(self, implementation, method):
        """
        A ``transmat_`` row that sums to 1 with a negative entry is refused,
        naming it, instead of scoring NaN and decoding states.
        """
        h = self.new_hmm(implementation)
        h.transmat_ = np.array([[1.2, -0.2], [0.4, 0.6]])
        X = np.array([[0, 1, 2, 0, 2]]).T
        # Without the check the NaN arithmetic would warn; ignoring it lets
        # a missing refusal show as one.
        with (
            np.errstate(all="ignore"),
            pytest.raises(ValueError, match="transmat_"),
        ):
            getattr(h, method)(X)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_fit_counts_symbols_from_a_kept_emissionprob_as_fit_alone(
        self, implementation
    ):
        """
        A ``score`` leaves nothing for a later ``fit``: without
        ``n_features``, ``fit`` takes the number of symbols from a kept
        ``emissionprob_`` with more symbols than ``X`` shows, with or
        without a ``score`` before it, and fits as the model given that
        number.
        """
        X = np.array([[0, 1, 1, 0, 1]]).T
        expected = self.new_hmm(implementation)
        expected.init_params = ""
        expected.n_features = 3
        expected.fit(X)
        for score_first in (False, True):
            h = self.new_hmm(implementation)
            h.init_params = ""
            if score_first:
                h.score(X)
            h.fit(X)
            assert h.n_features == 3
            assert _fit_bytes(h) == _fit_bytes(expected)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_fit_refuses_a_symbol_beyond_a_kept_emissionprob(
        self, implementation
    ):
        """
        Without ``n_features``, ``fit`` refuses a symbol that a kept
        ``emissionprob_`` does not emit, naming it, and leaves
        ``n_features`` unset; ``X`` that shows every symbol stores the
        count ``X`` gives, of its type.
        """
        h = self.new_hmm(implementation)
        h.init_params = ""
        with pytest.raises(ValueError, match="Largest symbol is 3"):
            h.fit(np.array([[0, 3, 1]]).T)
        assert h.n_features is None
        X = np.array([[0, 1, 2, 1]]).T
        h = self.new_hmm(implementation)
        h.init_params = ""
        h.fit(X)
        assert h.n_features == 3
        assert type(h.n_features) is type(X.max() + 1)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_score_samples(self, implementation):
        idx = np.repeat(np.arange(self.n_components), 10)
        n_samples = len(idx)
        X = np.random.randint(self.n_features, size=(n_samples, 1))
        h = self.new_hmm(implementation)

        _ll, posteriors = h.score_samples(X)
        assert posteriors.shape == (n_samples, self.n_components)
        assert_allclose(posteriors.sum(axis=1), np.ones(n_samples))

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_sample(self, implementation, n_samples=1000):
        h = self.new_hmm(implementation)
        X, state_sequence = h.sample(n_samples)
        assert X.ndim == 2
        assert len(X) == len(state_sequence) == n_samples
        assert len(np.unique(X)) == self.n_features

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_fit(self, implementation, params="ste", n_iter=5):

        h = self.new_hmm(implementation)
        h.params = params

        lengths = np.array([10] * 10)
        X, _state_sequence = h.sample(lengths.sum())

        # Mess up the parameters and see if we can re-learn them.
        h.startprob_ = normalized(np.random.random(self.n_components))
        h.transmat_ = normalized(
            np.random.random((self.n_components, self.n_components)), axis=1
        )
        h.emissionprob_ = normalized(
            np.random.random((self.n_components, self.n_features)), axis=1
        )

        assert_log_likelihood_increasing(h, X, lengths, n_iter)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_fit_emissionprob(self, implementation):
        self.test_fit(implementation, "e")

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_fit_with_init(self, implementation, params="ste", n_iter=5):
        lengths = [10] * 10
        h = self.new_hmm(implementation)
        X, _state_sequence = h.sample(sum(lengths))

        # use init_function to initialize paramerters
        h = hmm.CategoricalHMM(
            self.n_components, params=params, init_params=params
        )
        h._init(X, lengths)

        assert_log_likelihood_increasing(h, X, lengths, n_iter)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    @pytest.mark.parametrize(
        "method",
        ["score", "score_samples", "decode", "predict", "predict_proba"],
    )
    @pytest.mark.parametrize("symbol", [-1, 3, 1.5, -1.0])
    def test_prediction_refuses_symbols_outside_range(
        self, symbol, method, implementation
    ):
        """
        A symbol that is negative, not a whole number, or not below
        ``n_features`` is refused, naming ``X``, instead of being read as a
        column of ``emissionprob_`` counted from the end or failing on the
        index.
        """
        h = self.new_hmm(implementation)
        X = np.array([[0], [symbol], [2]])
        with pytest.raises(ValueError, match="X must contain symbols"):
            getattr(h, method)(X)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    @pytest.mark.parametrize("symbol, probability", [(0, 0.30), (2, 0.34)])
    def test_symbols_at_the_range_ends_score(
        self, symbol, probability, implementation
    ):
        """
        The symbols ``0`` and ``n_features - 1`` stay valid: one sample
        scores the log of ``startprob_ @ emissionprob_[:, symbol]``
        (``0.6 * 0.1 + 0.4 * 0.6`` and ``0.6 * 0.5 + 0.4 * 0.1``).
        """
        h = self.new_hmm(implementation)
        assert_allclose(h.score([[symbol]]), np.log(probability), rtol=1e-12)

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test_two_column_layout_scores_as_one_sequence(self, implementation):
        """
        The deprecated ``(n_samples, 2)`` layout still scores, with a
        ``DeprecationWarning``, as the ``(2 * n_samples, 1)`` sequence it is
        read as.
        """
        h = self.new_hmm(implementation)
        X = np.array([[0, 1], [2, 0], [1, 1]])
        with pytest.warns(DeprecationWarning, match="deprecated"):
            score = h.score(X)
        assert score == h.score(X.reshape(-1, 1))

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    @pytest.mark.parametrize("method", ["score", "predict", "decode"])
    @pytest.mark.parametrize(
        "emissionprob, X",
        [
            ([[1.0], [1.0]], [[True]]),
            ([[0.3, 0.7], [0.8, 0.2]], [[True], [False]]),
            ([[0.3, 0.7], [0.8, 0.2]], [[False]]),
            ([[0.1, 0.4, 0.5], [0.6, 0.3, 0.1]], [[True], [False], [True]]),
        ],
        ids=["1-symbol-T", "2-symbols-TF", "2-symbols-F", "3-symbols-TFT"],
    )
    def test_prediction_refuses_boolean_X(
        self, emissionprob, X, method, implementation
    ):
        """
        A boolean ``X`` is refused, naming ``X``, as ``fit`` refuses it:
        NumPy reads a boolean array as a mask over the symbols, not as the
        symbols 0 and 1.
        """
        h = self.new_hmm(implementation)
        h.emissionprob_ = np.array(emissionprob)
        with pytest.raises(ValueError, match="X must .*not booleans"):
            getattr(h, method)(np.array(X))

    @pytest.mark.parametrize("implementation", ["scaling", "log"])
    def test__check_and_set_categorical_n_features(self, implementation):
        h = self.new_hmm(implementation)
        h._check_and_set_n_features(np.array([[0, 0, 2, 1, 3, 1, 1]]).T)
        h._check_and_set_n_features(np.array([[0, 0, 1, 3, 1]], np.uint8))
        with pytest.raises(ValueError):  # non-integral
            h._check_and_set_n_features(np.array([[0.0, 2.0, 1.0, 3.0]]))
        with pytest.raises(ValueError):  # negative integers
            h._check_and_set_n_features(np.array([[0, -2, 1, 3, 1, 1]]))
